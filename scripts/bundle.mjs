import fs from 'node:fs';
const bank=JSON.parse(fs.readFileSync('src/bank.json','utf8'));
const css=fs.readFileSync('src/style.css','utf8');
const client=fs.readFileSync('src/app.js','utf8');
const core=fs.readFileSync('src/core.js','utf8').replaceAll('export ','');
const html=fs.readFileSync('src/index.html','utf8').replace('/*STYLE*/',css).replace('/*DATA*/','const BANK = '+JSON.stringify(bank).replaceAll('<','\\u003c')+';').replace('/*CORE*/',core).replace('/*APP*/',client);
const server=fs.readFileSync('src/server.js','utf8');
fs.writeFileSync('worker/index.js','// Generated by scripts/bundle.mjs. Edit src/ instead.\nconst BANK = '+JSON.stringify(bank)+';\nconst page = '+JSON.stringify(html)+';\n'+server);
console.log('Bundled '+bank.length+' practice questions.');
